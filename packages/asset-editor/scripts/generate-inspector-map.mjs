import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const filename = fileURLToPath(import.meta.url);
const scriptDir = resolve(filename, '..');
const packageRoot = resolve(scriptDir, '..');
const srcRoot = join(packageRoot, 'src');
const registryPath = join(srcRoot, 'lib', 'core', 'registry', 'inspectorMap.generated.ts');

const IGNORE_DIRS = new Set([
  '__tests__',
  'test',
  'tests',
  'node_modules',
  '.git',
  '.cache',
  '.vite',
  'dist',
  'coverage',
  '.turbo',
]);
const INSPECTOR_FILE = /Inspector\.(tsx|ts)$/;

function getInspectorFilePaths(rootDir, out = []) {
  const entries = readdirSync(rootDir);
  for (const entry of entries) {
    const fullPath = join(rootDir, entry);
    const stats = statSync(fullPath);
    if (stats.isDirectory()) {
      if (IGNORE_DIRS.has(entry)) continue;
      getInspectorFilePaths(fullPath, out);
      continue;
    }
    if (!INSPECTOR_FILE.test(entry)) continue;
    out.push(fullPath);
  }
  return out;
}

function isInspectorMapUpToDate() {
  try {
    const outStat = statSync(registryPath);
    const dirs = [
      join(srcRoot, 'lib', 'assets'),
      join(srcRoot, 'lib', 'core', 'inspector', 'components'),
    ];
    let maxInputMtime = 0;
    for (const dir of dirs) {
      try {
        for (const p of getInspectorFilePaths(dir)) {
          const m = statSync(p).mtimeMs;
          if (m > maxInputMtime) maxInputMtime = m;
        }
      } catch {
        return false;
      }
    }
    return outStat.mtimeMs >= maxInputMtime;
  } catch {
    return false;
  }
}

const aliasTargets = {
  AssetRegistry: 'ExportIndex',
  DifferentColorsSequence: 'BaseBonusRule',
  FiveOfAKind: 'BaseBonusRule',
  Flush: 'BaseBonusRule',
  FourOfAKind: 'BaseBonusRule',
  FullHouse: 'BaseBonusRule',
  HighCard: 'BaseBonusRule',
  MultipleFourOfAKind: 'BaseBonusRule',
  MultiplePairs: 'BaseBonusRule',
  MultipleTriplets: 'BaseBonusRule',
  PairRule: 'BaseBonusRule',
  RoyalFlush: 'BaseBonusRule',
  SameColorsSequence: 'BaseBonusRule',
  StraightFlush: 'BaseBonusRule',
  ThreeOfAKind: 'BaseBonusRule',
  TrumpOfAKind: 'BaseBonusRule',
  CardGameLayout: 'Layout',
};

function scanInspectors(rootDir, inspectorMap) {
  const walk = (currentDir) => {
    const entries = readdirSync(currentDir);
    for (const entry of entries) {
      const fullPath = join(currentDir, entry);
      const stats = statSync(fullPath);
      if (stats.isDirectory()) {
        if (IGNORE_DIRS.has(entry)) {
          continue;
        }
        walk(fullPath);
        continue;
      }
      if (!INSPECTOR_FILE.test(entry)) {
        continue;
      }
      const assetType = entry.replace(/Inspector\.(tsx|ts)$/, '');
      const relPath = relative(srcRoot, fullPath).replace(/\\/g, '/').replace(/\.(tsx|ts)$/, '');
      inspectorMap[assetType] = `@/${relPath}`;
    }
  };

  walk(rootDir);
}

function buildInspectorMap() {
  const inspectorMap = {};
  scanInspectors(join(srcRoot, 'lib', 'assets'), inspectorMap);
  scanInspectors(join(srcRoot, 'lib', 'core', 'inspector', 'components'), inspectorMap);

  for (const [aliasType, targetType] of Object.entries(aliasTargets)) {
    const targetPath = inspectorMap[targetType];
    if (targetPath) {
      inspectorMap[aliasType] = targetPath;
    }
  }

  return Object.fromEntries(Object.entries(inspectorMap).sort(([a], [b]) => a.localeCompare(b)));
}

function writeInspectorMapFile(inspectorMap) {
  const content = `// This file is auto-generated by scripts/generate-inspector-map.mjs
// Do not edit manually - it will be overwritten by tooling

export type ImportPath = string;

export const inspectorMap = ${JSON.stringify(inspectorMap, null, 2)} as const;

export type InspectorTypeName = keyof typeof inspectorMap;

export type InspectorMap = Record<InspectorTypeName, ImportPath>;
`;

  writeFileSync(registryPath, content, 'utf8');
}

if (isInspectorMapUpToDate()) {
  console.log('[generate-inspector-map] Unchanged, skipping');
} else {
  const generatedMap = buildInspectorMap();
  writeInspectorMapFile(generatedMap);
  console.log(`[generate-inspector-map] Generated ${Object.keys(generatedMap).length} entries`);
}
