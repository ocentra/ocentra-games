function normalizePlayerHubString(value: string): string {
  return STALE_PLAYER_HUB_COPY.get(value.trim()) ?? value;
}

function normalizePlayerHubStrings<T>(value: T): T {
  if (typeof value === 'string') {
    return normalizePlayerHubString(value) as T;
  }
  if (Array.isArray(value)) {
    return value.map(normalizePlayerHubStrings) as T;
  }
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as JsonRecord).map(([key, child]) => [key, normalizePlayerHubStrings(child)]),
    ) as T;
  }
  return value;
}

function assertKnownKeys(source: unknown, fallback: unknown, path: string) {
  if (!source || typeof source !== 'object' || Array.isArray(source) || !fallback || typeof fallback !== 'object' || Array.isArray(fallback)) {
    return;
  }
  const sourceRecord = source as JsonRecord;
  const fallbackRecord = fallback as JsonRecord;
  for (const key of Object.keys(sourceRecord)) {
    if (!(key in fallbackRecord)) {
      throw new Error(`Unknown Player Hub content field: ${path}.${key}`);
    }
    assertKnownKeys(sourceRecord[key], fallbackRecord[key], `${path}.${key}`);
  }
}

function mergeKnownValue<T>(fallback: T, source: unknown): T {
  if (Array.isArray(fallback)) {
    return Array.isArray(source) ? source as T : fallback;
  }
  if (fallback && typeof fallback === 'object') {
    const fallbackRecord = fallback as JsonRecord;
    const sourceRecord = asRecord(source);
    const merged: JsonRecord = { ...fallbackRecord };
    for (const [key, value] of Object.entries(fallbackRecord)) {
      merged[key] = mergeKnownValue(value, sourceRecord[key]);
    }
    return merged as T;
  }
  return typeof source === typeof fallback ? source as T : fallback;
}

