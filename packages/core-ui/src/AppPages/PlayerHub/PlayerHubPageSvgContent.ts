export function normalizePlayerHubPageContent(
  content?: PartialPlayerHubPageContentData | null,
): PlayerHubPageContentData {
  const fallback = cloneDefaultContent();
  if (content) {
    assertKnownKeys(content, fallback, 'playerHubContent');
    PartialPlayerHubPageContentDataSchema.parse(content);
  }
  const merged = mergeKnownValue(fallback, content);
  return PlayerHubPageContentDataSchema.parse(normalizePlayerHubStrings(merged));
}

export function parsePlayerHubPageContent(content: unknown): PlayerHubPageContentData {
  return PlayerHubPageContentDataSchema.parse(content);
}
